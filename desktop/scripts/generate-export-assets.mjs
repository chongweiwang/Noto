
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
let css = await readFile(new URL("node_modules/katex/dist/katex.min.css", root), "utf8");
const faces = [...css.matchAll(/@font-face\{[^}]+\}/g)];
for (const [face] of faces) {
  const name = face.match(/url\(fonts\/([^)]+\.woff2)\)/)?.[1];
  if (!name || /[\\/]/.test(name)) throw new Error("Unexpected KaTeX font declaration");
  const bytes = await readFile(new URL("node_modules/katex/dist/fonts/" + name, root));
  css = css.replace(face, face.replace(/src:[^;}]+/, 'src:url(data:font/woff2;base64,' + bytes.toString("base64") + ') format("woff2")'));
}
if (!faces.length || /url\((?!data:)/i.test(css)) throw new Error("KaTeX export contains non-embedded resources");
const license = await readFile(new URL("node_modules/katex/LICENSE", root), "utf8");
const result = "// Generated by scripts/generate-export-assets.mjs. Do not edit.\nexport const katexExportCss = " + JSON.stringify("/* " + license.replaceAll("*/", "* /") + " */\n" + css) + ";\n";
const target = new URL("src/lib/export-assets.generated.ts", root);
if (await readFile(target, "utf8").catch(() => "") !== result) await writeFile(target, result);
